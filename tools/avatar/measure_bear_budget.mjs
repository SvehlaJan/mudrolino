import fs from 'node:fs';
import crypto from 'node:crypto';
import { gzipSync } from 'node:zlib';
const root = 'assets/avatar/catalog-a/companions/bear-v1/';
const file = `${root}outfit-lod.glb`;
const bytes = fs.readFileSync(file);
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
const jsonLength = bytes.readUInt32LE(12);
const gltf = JSON.parse(bytes.subarray(20, 20 + jsonLength));
const binary = bytes.subarray(20 + jsonLength + 8);
const animation = gltf.animations[0];
if (gltf.animations.length !== 1 || animation.name !== 'celebrate') throw new Error('Unexpected clip');
const views = new Set();
for (const sampler of animation.samplers) for (const id of [sampler.input, sampler.output]) views.add(gltf.accessors[id].bufferView);
const clipPayloadBytes = [...views].reduce((sum, id) => sum + gltf.bufferViews[id].byteLength, 0);
const hip = animation.channels.find(channel => gltf.nodes[channel.target.node].name === 'Hips' && channel.target.path === 'translation');
if (!hip) throw new Error('No hips translation');
const accessor = gltf.accessors[animation.samplers[hip.sampler].output];
const view = gltf.bufferViews[accessor.bufferView];
if (accessor.componentType !== 5126 || accessor.type !== 'VEC3') throw new Error('Unexpected hips accessor');
const positions = Array.from({ length: accessor.count }, (_, i) => [0,1,2].map(axis => binary.readFloatLE((view.byteOffset ?? 0) + (accessor.byteOffset ?? 0) + i * (view.byteStride ?? 12) + axis * 4)));
const ranges = [0,1,2].map(axis => Math.max(...positions.map(p => p[axis])) - Math.min(...positions.map(p => p[axis])));
const first = positions[0], last = positions.at(-1);
const endpointHipsError = Math.hypot(...first.map((value, axis) => value - last[axis]));
const triangles = gltf.meshes.reduce((sum, mesh) => sum + mesh.primitives.reduce((n, primitive) => n + gltf.accessors[primitive.indices].count / 3, 0), 0);
const gzipBytes = gzipSync(bytes).length;
const construction = JSON.parse(fs.readFileSync(`${root}construction-report.json`));
const manifest = JSON.parse(fs.readFileSync('assets/avatar/asset-manifest.json'));
const baseline = Object.keys(manifest.files).find(file => file.startsWith(root) && file.endsWith('/outfit.glb') && manifest.files[file].sha256 === construction.glb_sha256);
if (!baseline) throw new Error('Matching static construction is not registered');
const staticBytes = fs.readFileSync(baseline);
const report = { status: triangles <= 95000 && gzipBytes <= 2100000 && ranges[0] < .000001 && ranges[2] < .000001 && ranges[1] <= .010001 && endpointHipsError < .000001 ? 'passed' : 'failed', model: file, glb_sha256: hash(bytes), verifier_sha256: hash(fs.readFileSync(new URL(import.meta.url))), triangles, bytes: bytes.length, gzip_bytes: gzipBytes, triangle_budget: 95000, gzip_budget: 2100000, clip_payload_buffer_bytes: clipPayloadBytes, clip_incremental_glb_bytes: bytes.length - staticBytes.length, clip_incremental_gzip_bytes: gzipBytes - gzipSync(staticBytes).length, static_reference: baseline, static_reference_sha256: hash(staticBytes), hips_translation: { coordinates: 'glTF Y-up', ranges_m: ranges, endpoint_error_m: endpointHipsError }, scope: 'Raw clip byte contribution and keyed pelvis envelope; all-surface runtime/floor proof is in runtime-report.json and native-dance-report.json' };
fs.writeFileSync(`${root}budget-report.json`, JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
if (report.status !== 'passed') process.exitCode = 1;
